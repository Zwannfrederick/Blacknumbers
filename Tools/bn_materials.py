tools = unreal.AssetToolsHelpers.get_asset_tools()
assets = unreal.EditorAssetLibrary
mel = unreal.MaterialEditingLibrary


def _load_or_create(name, path, cls, factory):
    full = "%s/%s" % (path, name)
    if assets.does_asset_exist(full):
        return unreal.load_asset(full)
    asset = tools.create_asset(name, path, cls, factory)
    if asset is None:
        raise RuntimeError("Could not create " + full)
    return asset


def _connect(src, src_pin, dst, dst_pin):
    if not mel.connect_material_expressions(src, src_pin, dst, dst_pin):
        raise RuntimeError("Failed to connect %s.%s -> %s.%s" % (src, src_pin, dst, dst_pin))


def _connect_prop(src, src_pin, prop):
    if not mel.connect_material_property(src, src_pin, prop):
        raise RuntimeError("Failed to connect %s.%s -> %s" % (src, src_pin, prop))


def _sampler_for(texture):
    """Matches the sampler type to the texture's compression & sRGB flags so the shader always compiles."""
    compression = texture.get_editor_property("compression_settings")
    srgb = texture.get_editor_property("srgb")
    if compression == unreal.TextureCompressionSettings.TC_NORMALMAP:
        return unreal.MaterialSamplerType.SAMPLERTYPE_NORMAL
    if compression == unreal.TextureCompressionSettings.TC_MASKS:
        return unreal.MaterialSamplerType.SAMPLERTYPE_MASKS
    if compression == unreal.TextureCompressionSettings.TC_GRAYSCALE:
        return unreal.MaterialSamplerType.SAMPLERTYPE_GRAYSCALE if srgb else unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_GRAYSCALE
    if compression == unreal.TextureCompressionSettings.TC_ALPHA:
        return unreal.MaterialSamplerType.SAMPLERTYPE_ALPHA
    return unreal.MaterialSamplerType.SAMPLERTYPE_COLOR if srgb else unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR


def _mask(mat, src, r=False, g=False, b=False, x=0, y=0):
    m = mel.create_material_expression(mat, unreal.MaterialExpressionComponentMask, x, y)
    m.set_editor_property("r", r)
    m.set_editor_property("g", g)
    m.set_editor_property("b", b)
    _connect(src, "", m, "")
    return m


def _build_box_uv(mat, tile_scale):
    """Single-tap world-space box UV projection (XY on floors/roofs, XZ/YZ upright on walls)."""
    world = mel.create_material_expression(mat, unreal.MaterialExpressionWorldPosition, -1900, 400)
    to_m = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, -1700, 400)
    to_m.set_editor_property("const_b", 0.01)
    _connect(world, "", to_m, "A")

    scaled = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, -1500, 400)
    _connect(to_m, "", scaled, "A")
    _connect(tile_scale, "", scaled, "B")

    px = _mask(mat, scaled, r=True, x=-1300, y=240)
    py = _mask(mat, scaled, g=True, x=-1300, y=360)
    pz = _mask(mat, scaled, b=True, x=-1300, y=480)
    neg_pz = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, -1120, 480)
    neg_pz.set_editor_property("const_b", -1.0)
    _connect(pz, "", neg_pz, "A")

    uv_xy = mel.create_material_expression(mat, unreal.MaterialExpressionAppendVector, -940, 240)
    _connect(px, "", uv_xy, "A")
    _connect(py, "", uv_xy, "B")

    uv_xz = mel.create_material_expression(mat, unreal.MaterialExpressionAppendVector, -940, 380)
    _connect(px, "", uv_xz, "A")
    _connect(neg_pz, "", uv_xz, "B")

    uv_yz = mel.create_material_expression(mat, unreal.MaterialExpressionAppendVector, -940, 520)
    _connect(py, "", uv_yz, "A")
    _connect(neg_pz, "", uv_yz, "B")

    vnorm = mel.create_material_expression(mat, unreal.MaterialExpressionVertexNormalWS, -1500, 720)
    anorm = mel.create_material_expression(mat, unreal.MaterialExpressionAbs, -1320, 720)
    _connect(vnorm, "", anorm, "")
    nx = _mask(mat, anorm, r=True, x=-1140, y=640)
    ny = _mask(mat, anorm, g=True, x=-1140, y=740)
    nz = _mask(mat, anorm, b=True, x=-1140, y=840)

    # Wall UV: if |Ny| > |Nx| use XZ else YZ
    wall_if = mel.create_material_expression(mat, unreal.MaterialExpressionIf, -720, 500)
    _connect(ny, "", wall_if, "A")
    _connect(nx, "", wall_if, "B")
    _connect(uv_xz, "", wall_if, "A > B")
    _connect(uv_xz, "", wall_if, "A == B")
    _connect(uv_yz, "", wall_if, "A < B")

    # Floor vs wall UV: if |Nz| > 0.5 use XY else wall UV
    final_if = mel.create_material_expression(mat, unreal.MaterialExpressionIf, -520, 360)
    final_if.set_editor_property("const_b", 0.5)
    _connect(nz, "", final_if, "A")
    _connect(uv_xy, "", final_if, "A > B")
    _connect(uv_xy, "", final_if, "A == B")
    _connect(wall_if, "", final_if, "A < B")
    return final_if


def _build_master(textures, mpc):
    mat = _load_or_create(MASTER, MAT_DIR, unreal.Material, unreal.MaterialFactoryNew())
    mel.delete_all_material_expressions(mat)
    mat.set_editor_property("used_with_instanced_static_meshes", True)

    def param(cls, name, default, x, y):
        p = mel.create_material_expression(mat, cls, x, y)
        p.set_editor_property("parameter_name", name)
        p.set_editor_property("default_value", default)
        return p

    def tex_param(name, tex_key, sampler_type, uv, x, y):
        t = mel.create_material_expression(mat, unreal.MaterialExpressionTextureSampleParameter2D, x, y)
        t.set_editor_property("parameter_name", name)
        t.set_editor_property("texture", textures[tex_key])
        t.set_editor_property("sampler_type", sampler_type)
        _connect(uv, "", t, "UVs")
        return t

    base_col = param(unreal.MaterialExpressionVectorParameter, "BaseColor", unreal.LinearColor(1, 1, 1, 1), -200, -520)
    tile_scale = param(unreal.MaterialExpressionScalarParameter, "TileScale", 0.25, -1720, 560)
    rough_max = param(unreal.MaterialExpressionScalarParameter, "Roughness", 0.85, -200, 120)
    rough_min = param(unreal.MaterialExpressionScalarParameter, "RoughnessMin", 0.20, -200, 220)
    puddle_amt = param(unreal.MaterialExpressionScalarParameter, "PuddleAmount", 0.0, -200, 20)
    specular = param(unreal.MaterialExpressionScalarParameter, "Specular", 0.50, 220, 20)
    metallic = param(unreal.MaterialExpressionScalarParameter, "Metallic", 0.0, 220, -80)
    normal_str = param(unreal.MaterialExpressionScalarParameter, "NormalStrength", 1.0, -200, 520)
    macro_var = param(unreal.MaterialExpressionScalarParameter, "MacroVariation", 0.14, -200, -180)
    emissive_const = param(unreal.MaterialExpressionVectorParameter, "Emissive", unreal.LinearColor(0, 0, 0, 1), -200, 760)
    emissive_mask_col = param(
        unreal.MaterialExpressionVectorParameter, "EmissiveMaskColor", unreal.LinearColor(0, 0, 0, 1), -200, 960
    )

    uv = _build_box_uv(mat, tile_scale)

    albedo_tex = tex_param("AlbedoMap", "T_White_D", unreal.MaterialSamplerType.SAMPLERTYPE_COLOR, uv, -260, -360)
    rough_tex = tex_param("RoughnessMap", "T_White_R", unreal.MaterialSamplerType.SAMPLERTYPE_MASKS, uv, -260, -20)
    normal_tex = tex_param("NormalMap", "T_Flat_N", unreal.MaterialSamplerType.SAMPLERTYPE_NORMAL, uv, -260, 340)
    emissive_tex = tex_param("EmissiveMap", "T_Black_E", unreal.MaterialSamplerType.SAMPLERTYPE_COLOR, uv, -260, 620)

    # Low-frequency macro noise breaks up tiling across long roads and wide plazas
    noise_tex = unreal.load_asset(MACRO_NOISE)
    macro_uv = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, -340, -160)
    macro_uv.set_editor_property("const_b", 0.06)
    _connect(uv, "", macro_uv, "A")
    macro_sample = mel.create_material_expression(mat, unreal.MaterialExpressionTextureSample, -60, -280)
    macro_sample.set_editor_property("texture", noise_tex)
    macro_sample.set_editor_property("sampler_type", _sampler_for(noise_tex))
    _connect(macro_uv, "", macro_sample, "UVs")

    # Macro world-space puddle mask (~85 m irregular puddles instead of repeating 5.5 m spots)
    wpos_p = mel.create_material_expression(mat, unreal.MaterialExpressionWorldPosition, -960, -680)
    wxy_p = _mask(mat, wpos_p, r=True, g=True, x=-760, y=-680)
    puddle_uv = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, -580, -680)
    puddle_uv.set_editor_property("const_b", 0.00011)
    _connect(wxy_p, "", puddle_uv, "A")
    puddle_noise = mel.create_material_expression(mat, unreal.MaterialExpressionTextureSample, -360, -720)
    puddle_noise.set_editor_property("texture", noise_tex)
    puddle_noise.set_editor_property("sampler_type", _sampler_for(noise_tex))
    _connect(puddle_uv, "", puddle_noise, "UVs")
    puddle_sub = mel.create_material_expression(mat, unreal.MaterialExpressionSubtract, -120, -700)
    puddle_sub.set_editor_property("const_b", 0.56)
    _connect(puddle_noise, "R", puddle_sub, "A")
    puddle_gain = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, 40, -700)
    puddle_gain.set_editor_property("const_b", 4.2)
    _connect(puddle_sub, "", puddle_gain, "A")
    puddle_clamp = mel.create_material_expression(mat, unreal.MaterialExpressionClamp, 200, -700)
    puddle_clamp.set_editor_property("min_default", 0.0)
    puddle_clamp.set_editor_property("max_default", 1.0)
    _connect(puddle_gain, "", puddle_clamp, "")
    wet_alpha = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, 360, -640)
    _connect(puddle_clamp, "", wet_alpha, "A")
    _connect(puddle_amt, "", wet_alpha, "B")

    one_minus_mv = mel.create_material_expression(mat, unreal.MaterialExpressionOneMinus, 80, -180)
    _connect(macro_var, "", one_minus_mv, "")
    macro_shade = mel.create_material_expression(mat, unreal.MaterialExpressionLinearInterpolate, 220, -240)
    macro_shade.set_editor_property("const_b", 1.0)
    _connect(one_minus_mv, "", macro_shade, "A")
    _connect(macro_sample, "R", macro_shade, "Alpha")

    tinted = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, 80, -420)
    _connect(albedo_tex, "RGB", tinted, "A")
    _connect(base_col, "", tinted, "B")
    macro_albedo = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, 340, -340)
    _connect(tinted, "", macro_albedo, "A")
    _connect(macro_shade, "", macro_albedo, "B")
    wet_darken = mel.create_material_expression(mat, unreal.MaterialExpressionLinearInterpolate, 440, -520)
    wet_darken.set_editor_property("const_a", 1.0)
    wet_darken.set_editor_property("const_b", 0.64)
    _connect(wet_alpha, "", wet_darken, "Alpha")
    final_albedo = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, 580, -360)
    _connect(macro_albedo, "", final_albedo, "A")
    _connect(wet_darken, "", final_albedo, "B")

    # Roughness: Lerp(base_rough, 0.10, wet_alpha) clamped to [0.04, 1.0]
    rough_lerp = mel.create_material_expression(mat, unreal.MaterialExpressionLinearInterpolate, 140, 120)
    _connect(rough_min, "", rough_lerp, "A")
    _connect(rough_max, "", rough_lerp, "B")
    _connect(rough_tex, "R", rough_lerp, "Alpha")
    rough_wet = mel.create_material_expression(mat, unreal.MaterialExpressionLinearInterpolate, 320, 120)
    rough_wet.set_editor_property("const_b", 0.10)
    _connect(rough_lerp, "", rough_wet, "A")
    _connect(wet_alpha, "", rough_wet, "Alpha")
    rough_clamp = mel.create_material_expression(mat, unreal.MaterialExpressionClamp, 500, 120)
    rough_clamp.set_editor_property("min_default", 0.04)
    rough_clamp.set_editor_property("max_default", 1.0)
    _connect(rough_wet, "", rough_clamp, "")

    # Normal: Lerp((0, 0, 1), NormalMap, NormalStrength)
    flat_vec = mel.create_material_expression(mat, unreal.MaterialExpressionConstant3Vector, -40, 420)
    flat_vec.set_editor_property("constant", unreal.LinearColor(0.0, 0.0, 1.0, 1.0))
    final_normal = mel.create_material_expression(mat, unreal.MaterialExpressionLinearInterpolate, 240, 380)
    _connect(flat_vec, "", final_normal, "A")
    _connect(normal_tex, "RGB", final_normal, "B")
    _connect(normal_str, "", final_normal, "Alpha")

    # Emissive: Emissive + EmissiveMap.RGB * EmissiveMaskColor * MPC_BN_World.NightFactor
    night_f = bn_materials_special.add_night_factor_node(mat, mel, mpc, -40, 1080)
    em_masked = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, 120, 840)
    _connect(emissive_tex, "RGB", em_masked, "A")
    _connect(emissive_mask_col, "", em_masked, "B")
    em_night = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, 280, 920)
    _connect(em_masked, "", em_night, "A")
    _connect(night_f, "", em_night, "B")
    final_emissive = mel.create_material_expression(mat, unreal.MaterialExpressionAdd, 460, 760)
    _connect(emissive_const, "", final_emissive, "A")
    _connect(em_night, "", final_emissive, "B")

    _connect_prop(final_albedo, "", unreal.MaterialProperty.MP_BASE_COLOR)
    _connect_prop(metallic, "", unreal.MaterialProperty.MP_METALLIC)
    _connect_prop(specular, "", unreal.MaterialProperty.MP_SPECULAR)
    _connect_prop(rough_clamp, "", unreal.MaterialProperty.MP_ROUGHNESS)
    _connect_prop(final_normal, "", unreal.MaterialProperty.MP_NORMAL)
    _connect_prop(final_emissive, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)

    mel.recompile_material(mat)
    return mat


def build():
    """Returns ({instance name: MaterialInstanceConstant}, {physical name: PhysicalMaterial})."""
    textures = bn_pbr_textures.ensure_ue_textures()

    physical = {}
    for name, friction in PHYSICAL.items():
        pm = _load_or_create(name, PHYS_DIR, unreal.PhysicalMaterial, unreal.PhysicalMaterialFactoryNew())
        pm.set_editor_property("friction", friction)
        # Zero restitution prevents Chaos vehicles from bouncing/launching off walls, curbs, or barriers.
        pm.set_editor_property("restitution", 0.0)
        pm.set_editor_property("override_restitution_combine_mode", True)
        pm.set_editor_property("restitution_combine_mode", unreal.FrictionCombineMode.MIN)
        physical[name] = pm

    mpc = bn_materials_special.ensure_world_mpc(MAT_DIR, _load_or_create)
    master = _build_master(textures, mpc)
    instances = {}
    for name, cfg in SURFACES.items():
        mi = _load_or_create(name, MAT_DIR, unreal.MaterialInstanceConstant, unreal.MaterialInstanceConstantFactoryNew())
        mel.set_material_instance_parent(mi, master)
        mel.clear_all_material_instance_parameters(mi)

        bc = cfg.get("base_color", (1.0, 1.0, 1.0))
        mel.set_material_instance_vector_parameter_value(mi, "BaseColor", unreal.LinearColor(*bc, 1.0))
        mel.set_material_instance_scalar_parameter_value(mi, "TileScale", float(cfg.get("tile_scale", 0.25)))
        mel.set_material_instance_scalar_parameter_value(mi, "Roughness", float(cfg.get("roughness", 0.85)))
        mel.set_material_instance_scalar_parameter_value(mi, "RoughnessMin", float(cfg.get("roughness_min", 0.20)))
        mel.set_material_instance_scalar_parameter_value(mi, "PuddleAmount", float(cfg.get("puddle_amount", 0.0)))
        mel.set_material_instance_scalar_parameter_value(mi, "Specular", float(cfg.get("specular", 0.50)))
        mel.set_material_instance_scalar_parameter_value(mi, "Metallic", float(cfg.get("metallic", 0.0)))
        mel.set_material_instance_scalar_parameter_value(mi, "NormalStrength", float(cfg.get("normal_strength", 1.0)))
        mel.set_material_instance_scalar_parameter_value(mi, "MacroVariation", float(cfg.get("macro_var", 0.14)))

        if "albedo" in cfg:
            mel.set_material_instance_texture_parameter_value(mi, "AlbedoMap", textures[cfg["albedo"]])
        if "normal" in cfg:
            mel.set_material_instance_texture_parameter_value(mi, "NormalMap", textures[cfg["normal"]])
        if "roughness_map" in cfg:
            mel.set_material_instance_texture_parameter_value(mi, "RoughnessMap", textures[cfg["roughness_map"]])
        if "emissive_map" in cfg:
            mel.set_material_instance_texture_parameter_value(mi, "EmissiveMap", textures[cfg["emissive_map"]])
        if "emissive" in cfg:
            mel.set_material_instance_vector_parameter_value(mi, "Emissive", unreal.LinearColor(*cfg["emissive"], 1.0))
        if "emissive_mask_color" in cfg:
            mel.set_material_instance_vector_parameter_value(
                mi, "EmissiveMaskColor", unreal.LinearColor(*cfg["emissive_mask_color"], 1.0)
            )

        mel.update_material_instance(mi)
        instances[name] = mi

    def _param(mat, cls, pname, default, x, y):
        p = mel.create_material_expression(mat, cls, x, y)
        p.set_editor_property("parameter_name", pname)
        p.set_editor_property("default_value", default)
        return p

    def _tex_param(mat, pname, tex_obj, sampler_type, uv_node, x, y):
        t = mel.create_material_expression(mat, unreal.MaterialExpressionTextureSampleParameter2D, x, y)
        t.set_editor_property("parameter_name", pname)
        t.set_editor_property("texture", tex_obj)
        t.set_editor_property("sampler_type", sampler_type)
        _connect(uv_node, "", t, "UVs")
        return t

    special = bn_materials_special.build_special_materials(
        MAT_DIR,
        textures,
        mpc,
        {
            "load_or_create": _load_or_create,
            "connect": _connect,
            "connect_prop": _connect_prop,
            "mask": _mask,
            "param": _param,
            "tex_param": _tex_param,
        },
    )
    instances.update(special)

    if not assets.save_directory(ROOT, only_if_is_dirty=False, recursive=True):
        raise RuntimeError("Could not save " + ROOT)
    unreal.log("BN: built %d PBR material instances, MPC_BN_World, and %d physical materials" % (len(instances), len(physical)))
    return instances, physical
